// Build an <svg> for one icon. The SVG text comes only from ICONS above
// (never from a model), so using innerHTML here is safe.
function icon(name, size = 16) {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", size);
  svg.setAttribute("height", size);
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "1.8");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  svg.classList.add("icon");
  svg.innerHTML = ICONS[name] || "";
  return svg;
}

// Replace every <i data-icon="name" data-size="20"></i> in the page with its icon
function fillIcons(root = document) {
  root.querySelectorAll("i[data-icon]").forEach((slot) => {
    slot.replaceWith(icon(slot.dataset.icon, Number(slot.dataset.size) || 16));
  });
}
